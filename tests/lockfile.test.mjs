test('detectLockfiles finds lockfiles and ignores skip directories', () => {
  const tmp = mkdtempSync(join(tmpdir(), 'airtight-detect-'));
  try {
    writeFileSync(join(tmp, 'package-lock.json'), '{}');
    writeFileSync(join(tmp, 'Cargo.lock'), '');

    mkdirSync(join(tmp, 'subpkg'));
    writeFileSync(join(tmp, 'subpkg', 'yarn.lock'), '');

    // Ignored directories
    mkdirSync(join(tmp, 'node_modules'));
    writeFileSync(join(tmp, 'node_modules', 'package-lock.json'), '{}');
    mkdirSync(join(tmp, '.git'));
    writeFileSync(join(tmp, '.git', 'Cargo.lock'), '');

    const detected = detectLockfiles(tmp);
    const basenames = detected.map((p) => p.replace(tmp + '/', '')).sort();
    assert.deepEqual(basenames, ['Cargo.lock', 'package-lock.json', 'subpkg/yarn.lock']);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});

