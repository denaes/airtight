test('queryOsv maps advisories to Airtight finding shape', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'airtight-osv-'));
  const cacheFile = join(tmp, 'osv.json');

  const sampleVuln = {
    id: 'GHSA-p6mc-m468-83gw',
    summary: 'Prototype pollution in lodash',
    details: 'Versions of lodash prior to 4.17.21 are vulnerable to prototype pollution.',
    database_specific: {
      severity: 'HIGH',
      cwe_ids: ['CWE-1321'],
    },
    affected: [
      {
        package: { name: 'lodash', ecosystem: 'npm' },
        ranges: [
          {
            type: 'SEMVER',
            events: [{ introduced: '0' }, { fixed: '4.17.21' }],
          },
        ],
      },
    ],
  };

  writeFileSync(cacheFile, JSON.stringify({
    'npm:lodash@4.17.20': [sampleVuln],
  }));

  try {
    const deps = [
      { name: 'lodash', version: '4.17.20', ecosystem: 'npm', lockfile: 'package-lock.json' },
    ];

    const findings = await queryOsv(deps, { cacheDir: tmp, offline: true });
    assert.equal(findings.length, 1);

    const f = findings[0];
    assert.equal(f.rule, 'dep/npm-advisory');
    assert.equal(f.severity, 'high');
    assert.equal(f.confidence, 'confirmed');
    assert.equal(f.priority, 'P1');
    assert.equal(f.cwe, 'CWE-1321');
    assert.equal(f.message, 'Prototype pollution in lodash');
    assert.equal(f.fix, '4.17.21');
    assert.equal(f.file, 'package-lock.json');
    assert.match(f.id, /^[0-9a-f]{12}$/);
    assert.equal(f.package.name, 'lodash');
    assert.equal(f.package.version, '4.17.20');
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});

test('queryOsv batches requests up to 100 and caches responses', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'airtight-osv-batch-'));
  const originalFetch = globalThis.fetch;
  const batchesReceived = [];

  globalThis.fetch = async (url, opts) => {
    const body = JSON.parse(opts.body);
    batchesReceived.push(body.queries);
    return {
      ok: true,
      json: async () => ({
        results: body.queries.map((q) => {
          if (q.package.name === 'vuln-pkg') {
            return {
              vulns: [
                {
                  id: 'VULN-001',
                  summary: 'Sample vulnerability',
                  database_specific: { severity: 'CRITICAL', cwe_ids: ['CWE-79'] },
                  affected: [{ ranges: [{ events: [{ fixed: '2.0.0' }] }] }],
                },
              ],
            };
          }
          return {};
        }),
      }),
    };
  };

  try {
    const deps = [];
    for (let i = 0; i < 150; i++) {
      deps.push({
        name: i === 5 ? 'vuln-pkg' : `safe-pkg-${i}`,
        version: '1.0.0',
        ecosystem: 'npm',
        lockfile: 'package-lock.json',
      });
    }

    const findings = await queryOsv(deps, { cacheDir: tmp, offline: false });
    assert.equal(batchesReceived.length, 2);
    assert.equal(batchesReceived[0].length, 100);
    assert.equal(batchesReceived[1].length, 50);

    assert.equal(findings.length, 1);
    assert.equal(findings[0].severity, 'critical');
    assert.equal(findings[0].priority, 'P0');
    assert.equal(findings[0].cwe, 'CWE-79');
    assert.equal(findings[0].fix, '2.0.0');

    // Verify cache file was written to disk
    const cacheOnDisk = JSON.parse(readFileSync(join(tmp, 'osv.json'), 'utf8'));
    assert.ok('npm:vuln-pkg@1.0.0' in cacheOnDisk);
    assert.equal(cacheOnDisk['npm:vuln-pkg@1.0.0'].length, 1);

    // Run again with offline = true; it should read from disk without network
    const offlineFindings = await queryOsv(deps, { cacheDir: tmp, offline: true });
    assert.equal(offlineFindings.length, 1);
    assert.equal(offlineFindings[0].id, findings[0].id);
  } finally {
    globalThis.fetch = originalFetch;
    rmSync(tmp, { recursive: true, force: true });
  }
});

test('queryOsv fails open on network failure and timeout', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'airtight-osv-fail-'));
  const originalFetch = globalThis.fetch;

  globalThis.fetch = async () => {
    throw new Error('Network error ENOTFOUND api.osv.dev');
  };

  try {
    const deps = [
      { name: 'lodash', version: '4.17.20', ecosystem: 'npm', lockfile: 'package-lock.json' },
    ];

    // Must not throw error, returns empty results
    const findings = await queryOsv(deps, { cacheDir: tmp, offline: false, timeoutMs: 50 });
    assert.deepEqual(findings, []);
  } finally {
    globalThis.fetch = originalFetch;
    rmSync(tmp, { recursive: true, force: true });
  }
});
