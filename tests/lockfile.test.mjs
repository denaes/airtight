test('parseLockfile parses npm v1 package-lock.json', () => {
  const content = JSON.stringify({
    name: 'v1-app',
    version: '1.0.0',
    lockfileVersion: 1,
    dependencies: {
      lodash: {
        version: '4.17.20',
      },
      express: {
        version: '4.18.2',
        dependencies: {
          debug: {
            version: '2.6.9',
          },
        },
      },
    },
  });

  const res = parseLockfile('package-lock.json', content);
  assert.equal(res.dependencies.length, 3);
  assert.deepEqual(res.dependencies[0], {
    name: 'lodash',
    version: '4.17.20',
    ecosystem: 'npm',
    lockfile: 'package-lock.json',
  });
  assert.deepEqual(res.dependencies[1], {
    name: 'express',
    version: '4.18.2',
    ecosystem: 'npm',
    lockfile: 'package-lock.json',
  });
  assert.deepEqual(res.dependencies[2], {
    name: 'debug',
    version: '2.6.9',
    ecosystem: 'npm',
    lockfile: 'package-lock.json',
  });
});

